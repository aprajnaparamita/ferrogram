    #[test]
    fn parses_and_sorts_the_fixture() {
        let catalog = parse_catalog(FIXTURE).unwrap();
        assert_eq!(catalog.sections.len(), 2);
        assert_eq!(catalog.sections[0].name, "Alpha");
        assert_eq!(catalog.sections[0].section_index, Some(1));
        assert_eq!(catalog.sections[1].name, "Zeta");
        assert_eq!(catalog.sections[1].section_index, None);
        assert_eq!(catalog.sections[1].cells.len(), 0);
        let alpha = &catalog.sections[0];
        assert_eq!(alpha.kind, "object");
        assert_eq!(alpha.cells.len(), 2);
        assert_eq!(alpha.cells[0].name, "Eta");
        assert_eq!(alpha.cells[0].cell_index, Some(0));
        assert_eq!(alpha.cells[0].default_value.as_deref(), Some("0 in"));
        assert_eq!(alpha.cells[1].name, "Zeta");
        assert_eq!(alpha.cells[1].cell_index, None);
        assert_eq!(alpha.cells[1].default_value, None);
        assert_eq!(catalog.rows.len(), 2);
        assert_eq!(catalog.rows[0].section.as_deref(), Some("Alpha"));
        assert_eq!(catalog.rows[1].name, "visRowB");
        assert_eq!(catalog.rows[1].section, None);
        assert_eq!(
            catalog.cell_indices,
            vec![("visCellA".into(), 1), ("visCellB".into(), 2)]
        );
        assert_eq!(catalog.row_indices, vec![("visRowA".into(), 0)]);
        assert_eq!(
            catalog.section_indices,
            vec![("visSectionA".into(), 1), ("visSectionZ".into(), 2)]
        );
    }

    /// ADR 0015: the same input yields byte-identical output, twice.
    #[test]
    fn generation_is_deterministic() {
        let a = generate_outputs(FIXTURE).unwrap();
        let b = generate_outputs(FIXTURE).unwrap();
        assert_eq!(a, b);
        let text = std::fs::read_to_string(util::root().join(INPUT)).unwrap();
        let c = generate_outputs(&text).unwrap();
        let d = generate_outputs(&text).unwrap();
        assert_eq!(c, d);
    }

