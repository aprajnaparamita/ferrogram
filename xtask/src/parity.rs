//! `cargo xtask parity`: the parity matrix runner (ADR 0037, P4-09).
//!
//! Regenerates `docs/parity/controls.md` from the committed
//! `ui-spec/` data and the builtin command registry, or (with
//! `--check`) fails when the committed file differs. Unlike
//! `cargo xtask extract` it needs no `reference/`, so the gate can
//! enforce freshness everywhere including CI.

use std::path::Path;

use crate::extract::util::write_atomic;
use crate::util::{self, Result};

/// `cargo xtask parity` arguments.
#[derive(Debug, Default, Clone, Copy, PartialEq, Eq)]
pub struct Options {
    /// Fail when the committed file differs instead of rewriting it.
    pub check: bool,
}

/// Parses `cargo xtask parity` arguments.
pub fn parse_args(args: &[String]) -> Result<Options> {
    let mut options = Options::default();
    for arg in args {
        match arg.as_str() {
            "--check" => options.check = true,
            other => return Err(format!("unknown parity argument `{other}`")),
        }
    }
    Ok(options)
}

/// Regenerates `docs/parity/controls.md`, or checks it for freshness.
pub fn run(options: &Options) -> Result<()> {
    run_in(&util::root(), options)
}

/// [`run`] over an explicit workspace root (the tests use a scratch
/// tree).
pub fn run_in(root: &Path, options: &Options) -> Result<()> {
    let text = crate::extract::parity::generate(root).map_err(|e| e.to_string())?;
    let path = root.join("docs").join("parity").join("controls.md");
    if options.check {
        let committed = std::fs::read_to_string(&path)
            .map_err(|e| format!("cannot read {}: {e}", path.display()))?;
        compare(&path, &committed, &text)
    } else {
        if let Some(parent) = path.parent() {
            std::fs::create_dir_all(parent)
                .map_err(|e| format!("cannot create {}: {e}", parent.display()))?;
        }
        write_atomic(&path, &text).map_err(|e| format!("cannot write {}: {e}", path.display()))?;
        println!("parity: wrote {}", path.display());
        Ok(())
    }
}

/// The freshness contract (the same as `codegen --check`): the
/// committed file must match the generated bytes exactly.
fn compare(path: &Path, committed: &str, generated: &str) -> Result<()> {
    if committed == generated {
        println!("parity --check: OK ({})", path.display());
        Ok(())
    } else {
        Err(format!(
            "{} is stale: run `cargo xtask parity` and commit the result \
             (ADR 0037)",
            path.display()
        ))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn no_args_checks_nothing() {
        assert_eq!(parse_args(&[]).unwrap(), Options::default());
    }

    #[test]
    fn check_flag_parses() {
        let args: Vec<String> = vec!["--check".to_owned()];
        assert_eq!(parse_args(&args).unwrap(), Options { check: true });
    }

    #[test]
    fn unknown_arguments_are_errors() {
        let args: Vec<String> = vec!["--bogus".to_owned()];
        assert!(
            parse_args(&args)
                .unwrap_err()
                .contains("unknown parity argument")
        );
    }

    #[test]
    fn a_fresh_file_checks_and_a_stale_file_fails() {
        assert!(compare(Path::new("docs/parity/controls.md"), "a\n", "a\n").is_ok());
        let error = compare(Path::new("docs/parity/controls.md"), "a\n", "b\n").unwrap_err();
        assert!(error.contains("is stale"), "{error}");
        assert!(error.contains("cargo xtask parity"), "{error}");
    }

    /// `run_in` over a scratch tree: `--check` passes when the file is
    /// fresh, fails when it is stale or missing, and the write mode
    /// regenerates it (ADR 0037's freshness contract end to end).
    #[test]
    fn run_in_writes_and_checks_a_scratch_tree() {
        let root = crate::util::test_support::TempDir::new("parity-run");
        // The generator's inputs: the committed ui-spec data.
        let ui_spec_src = util::root().join("ui-spec");
        let ui_spec_dst = root.join("ui-spec");
        std::fs::create_dir_all(&ui_spec_dst).unwrap();
        for name in [
            "panel-2016.yaml",
            "panel-365.yaml",
            "commands.yaml",
            "out-of-scope.txt",
        ] {
            std::fs::copy(ui_spec_src.join(name), ui_spec_dst.join(name)).unwrap();
        }

        // Write mode creates the file; check mode then passes.
        run_in(root.path(), &Options { check: false }).unwrap();
        let path = root.join("docs").join("parity").join("controls.md");
        let fresh = std::fs::read_to_string(&path).unwrap();
        assert!(fresh.contains("| status |"));
        run_in(root.path(), &Options { check: true }).unwrap();

        // Tamper: check mode fails, write mode restores freshness.
        std::fs::write(&path, "# tampered\n").unwrap();
        let error = run_in(root.path(), &Options { check: true }).unwrap_err();
        assert!(error.contains("is stale"), "{error}");
        run_in(root.path(), &Options { check: false }).unwrap();
        assert_eq!(std::fs::read_to_string(&path).unwrap(), fresh);
    }

    /// A missing committed file is a clean error, never a panic.
    #[test]
    fn a_missing_file_fails_the_check() {
        let root = crate::util::test_support::TempDir::new("parity-missing");
        let ui_spec_src = util::root().join("ui-spec");
        let ui_spec_dst = root.join("ui-spec");
        std::fs::create_dir_all(&ui_spec_dst).unwrap();
        for name in [
            "panel-2016.yaml",
            "panel-365.yaml",
            "commands.yaml",
            "out-of-scope.txt",
        ] {
            std::fs::copy(ui_spec_src.join(name), ui_spec_dst.join(name)).unwrap();
        }
        let error = run_in(root.path(), &Options { check: true }).unwrap_err();
        assert!(error.contains("cannot read"), "{error}");
    }
}
