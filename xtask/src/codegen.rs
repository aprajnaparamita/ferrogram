/// The Rust string-literal body of `s`, escaped and quoted.
fn literal(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    out.push('"');
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if c.is_control() => out.push_str(&format!("\\u{{{:x}}}", c as u32)),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

/// Renders `crates/model/src/generated/shapesheet.rs`.
fn render_shapesheet(catalog: &Catalog) -> String {
    let mut out = String::new();
    out.push_str(HEADER);
    out.push_str("\n\n");
    out.push_str(
        "//! The generated ShapeSheet catalogue: every section, row and cell\n\
         //! of Visio's ShapeSheet, plus the `Vis*Indices` enumerations\n\
         //! (ADR 0008).\n\
         //!\n\
         //! Generated from `ui-spec/shapesheet.toml` by `cargo xtask codegen`\n\
         //! (ADR 0015). Do not edit by hand: the gate step `codegen` runs\n\
         //! `cargo xtask codegen --check` and fails on drift.\n\n",
    );
    out.push_str(
        "/// One section of the ShapeSheet table.\n\
         #[derive(Debug, Clone, Copy, PartialEq, Eq)]\n\
         pub struct SectionDef {\n\
         \x20   /// The section name as Visio spells it.\n\
         \x20   pub name: &'static str,\n\
         \x20   /// The section's `VisSectionIndices` value, or `None`\n\
         \x20   /// when the table records none.\n\
         \x20   pub section_index: Option<i32>,\n\
         \x20   /// `\"object\"` for fixed one-row sections, `\"collection\"`\n\
         \x20   /// for sections whose rows repeat.\n\
         \x20   pub kind: &'static str,\n\
         \x20   /// The default unit of the section's cells.\n\
         \x20   pub default_unit: &'static str,\n\
         }\n\n\
         /// One row definition of the global rows table.\n\
         #[derive(Debug, Clone, Copy, PartialEq, Eq)]\n\
         pub struct RowDef {\n\
         \x20   /// The row's constant name (e.g. `\"visRowLine\"`).\n\
         \x20   pub name: &'static str,\n\
         \x20   /// The row's `VisRowIndices` value.\n\
         \x20   pub row_index: i32,\n\
         \x20   /// The name of the section that owns the row definition,\n\
         \x20   /// or `None` when the table records none.\n\
         \x20   pub section: Option<&'static str>,\n\
         }\n\n\
         /// One cell definition of one section.\n\
         #[derive(Debug, Clone, Copy, PartialEq, Eq)]\n\
         pub struct CellDef {\n\
         \x20   /// The cell name as Visio spells it.\n\
         \x20   pub name: &'static str,\n\
         \x20   /// The name of the section the cell lives in.\n\
         \x20   pub section: &'static str,\n\
         \x20   /// The cell's local index inside its row, or `None`\n\
         \x20   /// when the table records none.\n\
         \x20   pub cell_index: Option<i32>,\n\
         \x20   /// The cell type: `\"Number\"`, `\"String\"`, `\"Bool\"`,\n\
         \x20   /// `\"Color\"` or `\"List\"`.\n\
         \x20   pub kind: &'static str,\n\
         \x20   /// The cell's default unit.\n\
         \x20   pub default_unit: &'static str,\n\
         \x20   /// The cell's default value, when the table records one.\n\
         \x20   pub default_value: Option<&'static str>,\n\
         }\n\n",
    );

    out.push_str("/// Every ShapeSheet section, sorted by name.\n");
    out.push_str("pub static SECTIONS: &[SectionDef] = &[\n");
    for section in &catalog.sections {
        out.push_str("    SectionDef {\n");
        out.push_str(&format!("        name: {},\n", literal(&section.name)));
        match &section.section_index {
            Some(index) => out.push_str(&format!("        section_index: Some({index}),\n")),
            None => out.push_str("        section_index: None,\n"),
        }
        out.push_str(&format!("        kind: {},\n", literal(&section.kind)));
        out.push_str(&format!(
            "        default_unit: {},\n",
            literal(&section.default_unit)
        ));
        out.push_str("    },\n");
    }
    out.push_str("];\n\n");

    out.push_str("/// Every ShapeSheet row definition, sorted by name.\n");
    out.push_str("pub static ROWS: &[RowDef] = &[\n");
    for row in &catalog.rows {
        out.push_str("    RowDef {\n");
        out.push_str(&format!("        name: {},\n", literal(&row.name)));
        out.push_str(&format!("        row_index: {},\n", row.row_index));
        match &row.section {
            Some(name) => out.push_str(&format!("        section: Some({}),\n", literal(name))),
            None => out.push_str("        section: None,\n"),
        }
        out.push_str("    },\n");
    }
    out.push_str("];\n\n");

    out.push_str(
        "/// Every cell of every section, sorted by section name, then\n\
         /// cell name.\n",
    );
    out.push_str("pub static CELLS: &[CellDef] = &[\n");
    for section in &catalog.sections {
        for cell in &section.cells {
            out.push_str("    CellDef {\n");
            out.push_str(&format!("        name: {},\n", literal(&cell.name)));
            out.push_str(&format!("        section: {},\n", literal(&section.name)));
            match &cell.cell_index {
                Some(index) => {
                    out.push_str(&format!("        cell_index: Some({index}),\n"));
                }
                None => out.push_str("        cell_index: None,\n"),
            }
            out.push_str(&format!("        kind: {},\n", literal(&cell.kind)));
            out.push_str(&format!(
                "        default_unit: {},\n",
                literal(&cell.default_unit)
            ));
            match &cell.default_value {
                Some(v) => out.push_str(&format!("        default_value: Some({}),\n", literal(v))),
                None => out.push_str("        default_value: None,\n"),
            }
            out.push_str("    },\n");
        }
    }
    out.push_str("];\n\n");

    render_index_static(
        &mut out,
        "CELL_INDICES",
        "visCellIndices",
        &catalog.cell_indices,
    );
    render_index_static(
        &mut out,
        "SECTION_INDICES",
        "visSectionIndices",
        &catalog.section_indices,
    );
    render_index_static(
        &mut out,
        "ROW_INDICES",
        "visRowIndices",
        &catalog.row_indices,
    );

    out.push_str(
        "/// The definition of one cell of one section, by names, or `None`.\n\
         pub fn cell(section: &str, cell: &str) -> Option<&'static CellDef> {\n\
         \x20   CELLS\n\
         \x20       .iter()\n\
         \x20       .find(|c| c.section == section && c.name == cell)\n\
         }\n\n\
         /// The definition of one section, or `None`.\n\
         pub fn section(name: &str) -> Option<&'static SectionDef> {\n\
         \x20   SECTIONS.iter().find(|s| s.name == name)\n\
         }\n\n",
    );

    out.push_str(
        "#[cfg(test)]\n\
         mod tests {\n\
         \x20   use super::*;\n\n\
         \x20   /// Every cell of [`CELLS`] resolves through [`cell`].\n\
         \x20   #[test]\n\
         \x20   fn every_cell_resolves() {\n\
         \x20       for c in CELLS {\n\
         \x20           let found = cell(c.section, c.name).map(|d| d.cell_index);\n\
         \x20           assert_eq!(found, Some(c.cell_index), \"{}!{}\", c.section, c.name);\n\
         \x20       }\n\
         \x20   }\n\n\
         \x20   /// Every section of [`SECTIONS`] resolves through [`section`].\n\
         \x20   #[test]\n\
         \x20   fn every_section_resolves() {\n\
         \x20       for s in SECTIONS {\n\
         \x20           let found = section(s.name).map(|d| d.section_index);\n\
         \x20           assert_eq!(found, Some(s.section_index), \"{}\", s.name);\n\
         \x20       }\n\
         \x20   }\n\n\
         \x20   /// Unknown names resolve to `None`, never to a wrong entry.\n\
         \x20   #[test]\n\
         \x20   fn unknown_names_are_none() {\n\
         \x20       assert!(cell(\"\", \"\").is_none());\n\
         \x20       assert!(cell(\"NoSuchSection\", \"NoSuchCell\").is_none());\n\
         \x20       assert!(section(\"NoSuchSection\").is_none());\n\
         \x20   }\n\
         }\n",
    );
    out
}

/// Renders one `*INDICES` static from a sorted name-to-index map.
fn render_index_static(out: &mut String, name: &str, enum_name: &str, entries: &[(String, i32)]) {
    out.push_str(&format!(
        "/// The `{enum_name}` enumeration: name and index, sorted by name.\n"
    ));
    out.push_str(&format!("pub static {name}: &[(&str, i32)] = &[\n"));
    for (key, value) in entries {
        out.push_str(&format!("    ({}, {}),\n", literal(key), value));
    }
    out.push_str("];\n\n");
}

/// Renders `crates/model/src/generated/mod.rs`.
fn render_mod() -> String {
    let mut out = String::new();
    out.push_str(HEADER);
    out.push_str("\n\n");
    out.push_str(
        "//! The generated ShapeSheet catalogue (ADR 0008, ADR 0015).\n\
         //!\n\
         //! The tables live in [`shapesheet`] and are re-exported here.\n\
         //! They are generated from `ui-spec/shapesheet.toml` by\n\
         //! `cargo xtask codegen`; do not edit them by hand.\n\n\
         /// The generated ShapeSheet section, row and cell tables.\n\
         pub mod shapesheet;\n\n\
         pub use shapesheet::*;\n",
    );
    out
}

