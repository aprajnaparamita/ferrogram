//! `cargo xtask codegen`: turns `ui-spec/shapesheet.toml` into the
//! generated ShapeSheet table in `crates/model/src/generated/`
//! (ADR 0008, ADR 0015).
//!
//! The generation is deterministic: the same TOML always yields
//! byte-identical Rust (sorted iteration, no timestamps, no absolute
//! paths). `--check` regenerates into a scratch directory and compares
//! byte-for-byte with the committed files, the same contract as
//! `cargo xtask extract --check` (ADR 0009).

use std::path::{Path, PathBuf};

use crate::util::{self, Result};

/// `cargo xtask codegen` options.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub struct Options {
    /// When true, verify the committed generated files instead of
    /// rewriting them: fail on any drift (ADR 0015).
    pub check: bool,
}

/// The one committed input (read-only for this task).
const INPUT: &str = "ui-spec/shapesheet.toml";

/// The first line of every generated file (ADR 0015).
const HEADER: &str =
    "// GENERATED by `cargo xtask codegen` from `ui-spec/shapesheet.toml` — do not edit.";

/// Parses `cargo xtask codegen` arguments. Accepts the empty argument
/// list or `--check`; everything else is an error.
pub fn parse_args(args: &[String]) -> Result<Options> {
    let mut options = Options::default();
    for a in args {
        match a.as_str() {
            "--check" => options.check = true,
            other => return Err(format!("unknown codegen argument `{other}`")),
        }
    }
    Ok(options)
}

/// Runs `cargo xtask codegen`. Reads [`INPUT`], renders the generated
/// files, and either writes them into the workspace or (with
/// `--check`) verifies that the committed files match the rendering.
pub fn run(options: &Options) -> Result<()> {
    let root = util::root();
    let input = root.join(INPUT);
    let text = std::fs::read_to_string(&input)
        .map_err(|e| format!("cannot read {}: {e}", input.display()))?;
    let outputs = generate_outputs(&text)?;
    if options.check {
        check_outputs(&root, &outputs)?;
        println!("codegen --check: OK (the committed generated files are fresh)");
        Ok(())
    } else {
        write_outputs(&root, &outputs)?;
        for (rel, _) in &outputs {
            println!("codegen: wrote {}", rel.display());
        }
        Ok(())
    }
}

/// One generated file: its path relative to the workspace root and its
/// full content.
type Output = (PathBuf, String);

/// Parses the shapesheet table and renders every generated file, in a
/// fixed order: `shapesheet.rs`, then `mod.rs`.
fn generate_outputs(text: &str) -> Result<Vec<Output>> {
    let catalog = parse_catalog(text)?;
    Ok(vec![
        (
            PathBuf::from("crates/model/src/generated/shapesheet.rs"),
            render_shapesheet(&catalog),
        ),
        (
            PathBuf::from("crates/model/src/generated/mod.rs"),
            render_mod(),
        ),
    ])
}

/// Writes every output under `root`, creating parent directories.
fn write_outputs(root: &Path, outputs: &[Output]) -> Result<()> {
    for (rel, content) in outputs {
        util::write_atomic_bytes(&root.join(rel), content.as_bytes())?;
    }
    Ok(())
}

/// `--check` (ADR 0015): regenerates every output into a scratch
/// directory and compares it byte-for-byte with the committed file
/// under `root`. Returns an error that names each stale or missing
/// file and the command that fixes it. Line endings do not count: a
/// CRLF checkout compares equal to the LF the renderer writes.
fn check_outputs(root: &Path, outputs: &[Output]) -> Result<()> {
    let scratch = scratch_dir()?;
    let mut stale: Vec<String> = Vec::new();
    for (rel, content) in outputs {
        let fresh = scratch.join(rel);
        util::write_atomic_bytes(&fresh, content.as_bytes())?;
        if !same_bytes(&fresh, &root.join(rel)) {
            stale.push(rel.display().to_string());
        }
    }
    if stale.is_empty() {
        Ok(())
    } else {
        Err(format!(
            "codegen --check failed: generated file(s) stale or missing:\n  {}\n\
             fix: run `cargo xtask codegen` and commit the result",
            stale.join("\n  ")
        ))
    }
}

/// True when both paths hold the same content. A missing or unreadable
/// file is never equal to anything.
fn same_bytes(a: &Path, b: &Path) -> bool {
    match (std::fs::read(a), std::fs::read(b)) {
        (Ok(x), Ok(y)) => strip_cr(&x) == strip_cr(&y),
        _ => false,
    }
}

/// Drops carriage returns, so CRLF and LF compare equal.
fn strip_cr(bytes: &[u8]) -> Vec<u8> {
    bytes.iter().copied().filter(|b| *b != b'\r').collect()
}

/// A fresh scratch directory under the system temp dir. The name
/// carries the pid and a counter so parallel runs never collide.
fn scratch_dir() -> Result<PathBuf> {
    use std::sync::atomic::{AtomicUsize, Ordering};
    static COUNTER: AtomicUsize = AtomicUsize::new(0);
    let n = COUNTER.fetch_add(1, Ordering::Relaxed);
    let dir = std::env::temp_dir().join(format!(
        "ferrogram-codegen-check-{}-{n}",
        std::process::id()
    ));
    if dir.exists() {
        std::fs::remove_dir_all(&dir)
            .map_err(|e| format!("cannot clear {}: {e}", dir.display()))?;
    }
    std::fs::create_dir_all(&dir).map_err(|e| format!("cannot create {}: {e}", dir.display()))?;
    Ok(dir)
}

