    #[test]
    fn check_fails_on_a_stale_file_naming_the_file_and_the_fix() {
        let tmp = TempDir::new("codegen-stale");
        let outputs = outputs();
        write_outputs(tmp.path(), &outputs).unwrap();
        std::fs::write(
            tmp.join("crates/model/src/generated/shapesheet.rs"),
            "// hand-edited\n",
        )
        .unwrap();
        let err = check_outputs(tmp.path(), &outputs).unwrap_err();
        assert!(
            err.contains("crates/model/src/generated/shapesheet.rs"),
            "{err}"
        );
        assert!(err.contains("cargo xtask codegen"), "{err}");
    }

    #[test]
    fn check_fails_on_a_missing_file() {
        let tmp = TempDir::new("codegen-missing");
        let outputs = outputs();
        write_outputs(tmp.path(), &outputs).unwrap();
        std::fs::remove_file(tmp.join("crates/model/src/generated/mod.rs")).unwrap();
        let err = check_outputs(tmp.path(), &outputs).unwrap_err();
        assert!(err.contains("crates/model/src/generated/mod.rs"), "{err}");
        assert!(err.contains("fix: run `cargo xtask codegen`"), "{err}");
    }

    /// A CRLF copy of the generated file is not drift (same contract
    /// as `cargo xtask extract --check`, R6).
    #[test]
    fn check_tolerates_crlf() {
        let tmp = TempDir::new("codegen-crlf");
        let outputs = outputs();
        write_outputs(tmp.path(), &outputs).unwrap();
        for (rel, content) in &outputs {
            std::fs::write(tmp.join(rel), content.replace('\n', "\r\n")).unwrap();
        }
        check_outputs(tmp.path(), &outputs).unwrap();
    }
